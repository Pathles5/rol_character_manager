/* ============================================================
   FichaSS — characters manifest (Phase 10, T-02 / D-33).
   Types + structural validation + the single overview fetch.
   The manifest itself is GENERATED at build time by
   scripts/generate-manifest.mjs (plain Node) and copied to
   dist/ by Vite; this module only types and validates it, so
   a broken build artifact degrades into an amiable error state
   instead of a crash (D-35: never render partial data).
   ============================================================ */

export const MANIFEST_SCHEMA_VERSION = 1;

/** Escapes manifest/identity strings before innerHTML interpolation
    (review minor, Phase 10): the manifest is generated from trusted
    JSON at build time, but a hand-edited copy in the bucket is an
    injection vector — every string that reaches innerHTML goes
    through this. */
export function escapeHtml(text: string): string {
  return text.replace(/[&<>"']/g, ch => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch] as string
  );
}

/** One summary row of the manifest (generated by the build).
    `class` is the Spanish display class ("clériga"), not a
    TS class — mirrors identity.class of the character model. */
export interface ManifestEntry {
  /** File-name id: public/characters/<id>.json (lowercase kebab). */
  id: string;
  name: string;
  class: string;
  /** 1–20 (the validator's identity.level range). */
  level: number;
  /** Portrait initials, derived from the name at build time. */
  initials: string;
}

/** Root shape of characters-manifest.json (array order = listing
    order; the generator sorts by id). */
export interface CharacterManifest {
  schemaVersion: typeof MANIFEST_SCHEMA_VERSION;
  characters: ManifestEntry[];
}

/** Same id pattern the hash router enforces (src/router.ts);
    kept in sync by hand (both sides are one line, commented). */
export const CHARACTER_ID_PATTERN = /^[a-z0-9-]+$/;

export function isCharacterId(id: string): boolean {
  return CHARACTER_ID_PATTERN.test(id);
}

/** Type guard for one manifest entry: every field present and
    well-formed (id regex, non-empty strings, level 1–20). */
export function isManifestEntry(value: unknown): value is ManifestEntry {
  if (typeof value !== 'object' || value === null) return false;
  const entry = value as Record<string, unknown>;
  return (
    typeof entry.id === 'string' &&
    isCharacterId(entry.id) &&
    typeof entry.name === 'string' &&
    entry.name.trim().length > 0 &&
    typeof entry.class === 'string' &&
    entry.class.trim().length > 0 &&
    typeof entry.level === 'number' &&
    Number.isInteger(entry.level) &&
    entry.level >= 1 &&
    entry.level <= 20 &&
    typeof entry.initials === 'string' &&
    entry.initials.trim().length > 0
  );
}

/** Structural validation of a parsed manifest document; returns
    the entry array or null when the document is not a valid
    manifest (wrong version, non-array or malformed entries). */
export function parseManifest(value: unknown): ManifestEntry[] | null {
  if (typeof value !== 'object' || value === null) return null;
  const manifest = value as Record<string, unknown>;
  if (manifest.schemaVersion !== MANIFEST_SCHEMA_VERSION) return null;
  if (!Array.isArray(manifest.characters)) return null;
  if (!manifest.characters.every(isManifestEntry)) return null;
  return manifest.characters;
}

/** Fetches './characters-manifest.json' (relative: the build's
    base is './', so it works from any bucket prefix) and
    validates it. Throws on HTTP failure or malformed manifest:
    the overview view turns that into its error state. */
export async function loadManifest(): Promise<ManifestEntry[]> {
  const response = await fetch('./characters-manifest.json');
  if (!response.ok) {
    throw new Error(`characters-manifest.json: HTTP ${response.status}`);
  }
  const data: unknown = await response.json();
  const entries = parseManifest(data);
  if (!entries) {
    throw new Error('characters-manifest.json: invalid manifest document');
  }
  return entries;
}
